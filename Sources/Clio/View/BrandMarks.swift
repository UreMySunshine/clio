    /// Build a Path scaled into `rect` from the encoded segment list.
    static func path(_ encoded: String, in rect: CGRect) -> Path {
        var path = Path()
        let scale = min(rect.width, rect.height) / 16
        func point(_ x: Double, _ y: Double) -> CGPoint {
            CGPoint(x: rect.minX + x * scale, y: rect.minY + y * scale)
        }
        for segment in encoded.split(separator: "|") {
            let parts = segment.split(separator: " ")
            let values = parts.dropFirst().compactMap { Double($0) }
            switch parts.first {
            case "M" where values.count == 2:
                path.move(to: point(values[0], values[1]))
            case "L" where values.count == 2:
                path.addLine(to: point(values[0], values[1]))
            case "C" where values.count == 6:
                path.addCurve(to: point(values[4], values[5]),
                              control1: point(values[0], values[1]),
                              control2: point(values[2], values[3]))
            case "Z":
                path.closeSubpath()
            default:
                continue
            }
        }
        return path
    }
